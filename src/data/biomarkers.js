export const BIOMARKER_MAP = Object.fromEntries(BIOMARKERS.map((m) => [m.code, m]));

// Calculated biomarkers: computed from other values at evaluation time, never stored or shared.
const CALCULATORS = {
  tg_hdl_ratio: ({ triglycerides, hdl }) => (hdl > 0 ? triglycerides / hdl : null),
};

/** Adds calculated biomarkers a result has the inputs for (a value reported by the lab always wins). */
export function withDerived(result) {
  const values = new Map(result.results.map((e) => [e.code, e.value]));
  const extra = [];
  BIOMARKERS.filter((m) => m.derived && !values.has(m.code)).forEach((m) => {
    if (!m.derived.from.every((c) => Number.isFinite(values.get(c)))) return;
    const v = CALCULATORS[m.code](Object.fromEntries(m.derived.from.map((c) => [c, values.get(c)])));
    if (Number.isFinite(v)) extra.push({ code: m.code, value: Math.round(v * 100) / 100, derived: true });
  });
  return extra.length ? { ...result, results: [...result.results, ...extra] } : result;
}

/** Metadata for a code; unknown/custom markers get a minimal stub. */
export function getBiomarker(code, fallback = {}) {
  return (
    BIOMARKER_MAP[code] || {
      code,
      cat: 'other',
      unit: fallback.unit || '',
      name: { en: fallback.name || code, es: fallback.name || code },
      custom: true,
    }
  );
}
